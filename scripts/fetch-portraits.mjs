// Copies the PMD Collab "Normal" portraits (one per National Dex number, 1-1025; 0 is MissingNo and is skipped)
// into public/avatars/<Name>.png, the profile pictures users can pick. Also writes:
//   src/domain/avatars.ts        the allowed list, shared by the app and the server
//   public/avatars/CREDITS.md    the artists of every portrait
// Source: https://github.com/PMDCollab/SpriteCollab (CC BY-NC 4.0: non-commercial use, with credit to the artists).
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const RAW = 'https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'public', 'avatars');

async function get(url, as = 'text', tries = 4) {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return as === 'bytes' ? new Uint8Array(await res.arrayBuffer()) : await res.text();
    } catch (e) {
      if (i >= tries) throw e;
      await new Promise((r) => setTimeout(r, 500 * i));
    }
  }
}

const tracker = JSON.parse(await get(`${RAW}/tracker.json`));
// credit_names.txt is tab-separated: Name, Discord, Contact. The tracker credits artists by Discord id (or by name
// for a few); both map to the public name, which is all the credits file shows.
const creditNames = new Map();
for (const [name, discord] of (await get(`${RAW}/credit_names.txt`)).split('\n').slice(1).map((line) => line.split('\t'))) {
  if (!name?.trim()) continue;
  creditNames.set(name.trim(), name.trim());
  if (discord?.trim()) creditNames.set(discord.trim(), name.trim());
}

const entries = Object.keys(tracker)
  // Listed in portrait_files means the file exists (its true/false value means something else).
  .filter((id) => /^\d{4}$/.test(id) && Number(id) > 0 && 'Normal' in (tracker[id].portrait_files ?? {}))
  .sort()
  .map((id) => ({ id, dex: Number(id), name: String(tracker[id].name) }));

for (const e of entries) if (!/^[A-Za-z0-9_-]+$/.test(e.name)) throw new Error(`Unexpected name "${e.name}" for #${e.id}`);
if (new Set(entries.map((e) => e.name)).size !== entries.length) throw new Error('Duplicate names');

await mkdir(outDir, { recursive: true });
let done = 0;
const queue = [...entries];
await Promise.all(Array.from({ length: 8 }, async () => {
  for (let e = queue.shift(); e; e = queue.shift()) {
    await writeFile(join(outDir, `${e.name}.png`), await get(`${RAW}/portrait/${e.id}/Normal.png`, 'bytes'));
    if (++done % 100 === 0) console.log(`${done} / ${entries.length}`);
  }
}));

const credit = (id) => {
  const c = tracker[id].portrait_credit ?? {};
  // Artists missing from credit_names.txt are listed by their Discord id, without the chat markup.
  const named = (who) => creditNames.get(who) ?? (/^<@!?(\d+)>$/.test(who) ? `Discord user ${who.replace(/\D/g, '')}` : who);
  return [c.primary, ...(c.secondary ?? [])].filter(Boolean).map(named).join(', ') || 'unknown';
};
await writeFile(join(outDir, 'CREDITS.md'), [
  '# Profile picture credits',
  '',
  'Portraits from the [PMD Sprite Repository](https://github.com/PMDCollab/SpriteCollab), licensed under',
  '[CC BY-NC 4.0](https://creativecommons.org/licenses/by-nc/4.0/): non-commercial use only, with credit to the artists below.',
  '',
  '| # | Pokémon | Artists |',
  '| --- | --- | --- |',
  ...entries.map((e) => `| ${e.dex} | ${e.name.replace(/_/g, ' ')} | ${credit(e.id)} |`),
  '',
].join('\n'));

await writeFile(join(root, 'src', 'domain', 'avatars.ts'), [
  '// Generated by scripts/fetch-portraits.mjs (npm run avatars). Do not edit by hand.',
  '/** The profile pictures a user can have: file names in public/avatars, in National Dex order. */',
  `export const AVATARS: readonly string[] = ${JSON.stringify(entries.map((e) => e.name))};`,
  '',
].join('\n'));

console.log(`Copied ${entries.length} portraits to public/avatars`);
