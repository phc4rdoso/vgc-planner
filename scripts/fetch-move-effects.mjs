// Generates src/domain/move-effects.ts: each Champions move's added effects, from Pokémon Showdown's move data.
// The damage calculator only says that a move has secondary effects, not which; this fills that in, so the turn
// editor offers only real chance results and the simulation applies the guaranteed ones.
// Usage: npm run move-effects (needs network). The output is committed; run it again when the format's moves change.
import { writeFileSync } from 'node:fs';
import * as calc from '@smogon/calc';

const SOURCE = 'https://play.pokemonshowdown.com/data/moves.json';
const OUT = 'src/domain/move-effects.ts';
const STATS = ['atk', 'def', 'spa', 'spd', 'spe'];

// Moves whose effect is picked at random by the game (their data has a chance but no fixed effect).
const RANDOM = { triattack: ['brn', 'par', 'frz'], direclaw: ['psn', 'par', 'slp'] };

/** "atk+1" for one stat, "atk+1,def+1,..." when a move changes several together (Ancient Power). */
const boosts = (b) => STATS.filter((s) => b?.[s]).map((s) => `${s}${b[s] > 0 ? '+' : ''}${b[s]}`).join(',');

function effectsOf(id, move) {
  const target = { chance: [], always: [] };
  const self = { chance: [], always: [] };
  const list = move.secondaries ?? (move.secondary ? [move.secondary] : []);
  for (const s of list) {
    const bucket = s.chance === undefined || s.chance >= 100 ? 'always' : 'chance';
    if (RANDOM[id]) target.chance.push(...RANDOM[id]);
    if (s.status) target[bucket].push(s.status);
    if (s.volatileStatus === 'flinch' || s.volatileStatus === 'confusion') target[bucket].push(s.volatileStatus);
    if (s.boosts) target[bucket].push(boosts(s.boosts));
    if (s.self?.boosts) self[bucket].push(boosts(s.self.boosts));
  }
  // The user's own guaranteed changes after attacking (Close Combat, Draco Meteor...).
  if (move.category !== 'Status' && move.self?.boosts) self.always.push(boosts(move.self.boosts));
  const out = {};
  const put = (k, xs) => { const v = [...new Set(xs.filter(Boolean))]; if (v.length) out[k] = v; };
  put('chance', target.chance); put('always', target.always); put('selfChance', self.chance); put('selfAlways', self.always);
  return Object.keys(out).length ? out : null;
}

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: ${res.status}`);
const showdown = await res.json();
const gen = calc.Generations.get(0);
const champions = new Set([...gen.moves].map((m) => calc.toID(m.name)));
const table = {};
for (const id of [...champions].sort()) {
  const move = showdown[id];
  if (!move || move.category === 'Status') continue;
  const fx = effectsOf(id, move);
  if (fx) table[id] = fx;
}
const body = Object.entries(table).map(([id, fx]) => `  ${id}: ${JSON.stringify(fx).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")},`).join('\n');
writeFileSync(OUT, `/**
 * Added effects of the attacks in Pokémon Champions, by move id. Generated by scripts/fetch-move-effects.mjs from
 * Pokémon Showdown's move data: do not edit by hand (run \`npm run move-effects\`).
 * - \`chance\` / \`always\`: effects on the target that may happen / always happen (a condition, flinch, confusion,
 *   or stat changes like "spd-1"; several stats changing together are comma-joined).
 * - \`selfChance\` / \`selfAlways\`: the same for the user (Meteor Mash's chance of +1 Atk, Close Combat's drops).
 */
export interface MoveEffects { chance?: string[]; always?: string[]; selfChance?: string[]; selfAlways?: string[] }

export const MOVE_EFFECTS: Readonly<Record<string, MoveEffects>> = {
${body}
};
`);
console.log(`Wrote ${OUT}: ${Object.keys(table).length} attacks with added effects (of ${champions.size} moves).`);
